def run_champion_inference(
    input_file: Path,
    output_file: Path,
    start_record: Optional[int] = None,
    end_record: Optional[int] = None,
    record_ids_file: Optional[Path] = None,
    batch_size: int = BATCH_SIZE,
    cache_dir: Optional[Path] = None,
    clean_cache_after: bool = False,
) -> dict:
    """Execute complete champion ensemble inference on candidate listing titles."""
    overall_start_time = time.time()
    print("==================================================")
    print("CHAMPION ENSEMBLE INFERENCE PIPELINE (EXP 10)")
    print("==================================================")

    # 1. Device
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Device: {device}")
    if torch.cuda.is_available():
        vram = torch.cuda.get_device_properties(0).total_memory / (1024 ** 3)
        print(f"GPU: {torch.cuda.get_device_name(0)} ({vram:.2f} GB VRAM)")

    # 2. Parse explicit record IDs if provided
    explicit_ids = None
    if record_ids_file is not None and record_ids_file.exists():
        print(f"Loading explicit record IDs from {record_ids_file}...")
        explicit_ids = set()
        with open(record_ids_file, "r", encoding="utf-8") as f:
            for line in f:
                line_str = line.strip()
                if line_str and line_str.isdigit():
                    explicit_ids.add(int(line_str))
        print(f"Loaded {len(explicit_ids):,} explicit record IDs.")

    # 3. Load Candidate Records
    candidate_records = load_candidate_records(
        file_path=input_file,
        start_record=start_record,
        end_record=end_record,
        explicit_record_ids=explicit_ids,
    )
    if not candidate_records:
        raise ValueError("No candidate records found matching specifications!")

    # 4. Load label mapping from reference config
    ref_cfg = AutoConfig.from_pretrained(CHAMPION_CHECKPOINTS["gbert_seed42"])
    id2label = {int(k): v for k, v in ref_cfg.id2label.items()}
    label2id = {v: k for k, v in id2label.items()}
    o_label_id = label2id[O_LABEL_NAME]
    print(f"BIO classes: {len(id2label)} ('{O_LABEL_NAME}' ID = {o_label_id})")

    # 5. Model 1: GBERT (Weight = 0.40)
    print("\n--- [1/4] GBERT CHAMPION INFERENCE (WEIGHT = 0.40) ---")
    gbert_cache = (cache_dir / "test_probs_gbert.npy") if cache_dir else None
    gbert_tok = AutoTokenizer.from_pretrained(CHAMPION_CHECKPOINTS["gbert_seed42"])
    gbert_ds = CandidateTitleDataset(candidate_records, gbert_tok)
    t0_gb = time.time()
    gbert_probs = collect_model_probabilities(
        checkpoint_path=CHAMPION_CHECKPOINTS["gbert_seed42"],
        dataset=gbert_ds,
        device=device,
        o_label_id=o_label_id,
        num_classes=len(id2label),
        batch_size=batch_size,
        cache_file=gbert_cache,
    )
    print(f"GBERT completed in {time.time() - t0_gb:.1f}s.")
    del gbert_ds, gbert_tok

    # 6. Prepare Shared XLM-R Dataset
    print("\nPreparing shared XLM-R dataset for all 3 champion seeds...")
    xlmr_tok = AutoTokenizer.from_pretrained(CHAMPION_CHECKPOINTS["xlmr_seed42"])
    xlmr_ds = CandidateTitleDataset(candidate_records, xlmr_tok)

    # 7. Model 2: XLM-R Seed 42 (Weight = 0.20)
    print("\n--- [2/4] XLM-R SEED 42 INFERENCE (WEIGHT = 0.20) ---")
    s42_cache = (cache_dir / "test_probs_xlmr_seed42.npy") if cache_dir else None
    t0_42 = time.time()
    probs_42 = collect_model_probabilities(
        checkpoint_path=CHAMPION_CHECKPOINTS["xlmr_seed42"],
        dataset=xlmr_ds,
        device=device,
        o_label_id=o_label_id,
        num_classes=len(id2label),
        batch_size=batch_size,
        cache_file=s42_cache,
    )
    print(f"XLM-R seed 42 completed in {time.time() - t0_42:.1f}s.")
    xlmr_accum_probs = [p * (1.0 / 3.0) for p in probs_42]
    del probs_42

    # 8. Model 3: XLM-R Seed 7 (Weight = 0.20)
    print("\n--- [3/4] XLM-R SEED 7 INFERENCE (WEIGHT = 0.20) ---")
    s7_cache = (cache_dir / "test_probs_xlmr_seed7.npy") if cache_dir else None
    t0_7 = time.time()
    probs_7 = collect_model_probabilities(
        checkpoint_path=CHAMPION_CHECKPOINTS["xlmr_seed7"],
        dataset=xlmr_ds,
        device=device,
        o_label_id=o_label_id,
        num_classes=len(id2label),
        batch_size=batch_size,
        cache_file=s7_cache,
    )
    print(f"XLM-R seed 7 completed in {time.time() - t0_7:.1f}s.")
    for i in range(len(xlmr_accum_probs)):
        xlmr_accum_probs[i] += probs_7[i] * (1.0 / 3.0)
    del probs_7

    # 9. Model 4: XLM-R Seed 21 (Weight = 0.20)
    print("\n--- [4/4] XLM-R SEED 21 INFERENCE (WEIGHT = 0.20) ---")
    s21_cache = (cache_dir / "test_probs_xlmr_seed21.npy") if cache_dir else None
    t0_21 = time.time()
    probs_21 = collect_model_probabilities(
        checkpoint_path=CHAMPION_CHECKPOINTS["xlmr_seed21"],
        dataset=xlmr_ds,
        device=device,
        o_label_id=o_label_id,
        num_classes=len(id2label),
        batch_size=batch_size,
        cache_file=s21_cache,
    )
    print(f"XLM-R seed 21 completed in {time.time() - t0_21:.1f}s.")
    for i in range(len(xlmr_accum_probs)):
        xlmr_accum_probs[i] += probs_21[i] * (1.0 / 3.0)
    del probs_21
    del xlmr_ds, xlmr_tok

    # 10. Probability Fusion & Entity Extraction (Method A)
    print("\n==================================================")
    print("ENSEMBLE FUSION & SUBMISSION GENERATION (METHOD A)")
    print("==================================================")
    output_file.parent.mkdir(parents=True, exist_ok=True)

    rows_written = 0
    aspect_counts: Dict[str, int] = {}
    titles_with_entities = 0
    titles_without_entities = 0

    with open(output_file, "w", encoding="utf-8", newline="\n") as f:
        f.write("\t".join(OFFICIAL_HEADER) + "\n")

        for idx, (rec_id, cat_id, tokens) in enumerate(candidate_records):
            p_gbert = gbert_probs[idx]
            p_xlmr = xlmr_accum_probs[idx]

            # Invariant check
            if len(tokens) != len(p_gbert) or len(tokens) != len(p_xlmr):
                raise ValueError(f"Token length mismatch at record {rec_id}!")

            # 0.40 GBERT + 0.60 3-seed XLM-R
            p_fused = 0.40 * p_gbert + 0.60 * p_xlmr
            pred_ids = np.argmax(p_fused, axis=-1)
            pred_bio = [id2label[pid] for pid in pred_ids]

            entities = bio_to_entities(tokens, pred_bio)
            non_o_entities = [(asp, val) for asp, val in entities if asp != "O"]
            cat_valid_entities = filter_entities_by_category(non_o_entities, cat_id)

            if cat_valid_entities:
                titles_with_entities += 1
                for aspect_name, aspect_val in cat_valid_entities:
                    f.write(f"{rec_id}\t{cat_id}\t{aspect_name}\t{aspect_val}\n")
                    rows_written += 1
                    aspect_counts[aspect_name] = aspect_counts.get(aspect_name, 0) + 1
            else:
                titles_without_entities += 1

    total_runtime = time.time() - overall_start_time
    file_size_mb = output_file.stat().st_size / (1024 * 1024)
    sha256_hash = compute_sha256(output_file)

    print(f"\nSubmission File Written Successfully:")
    print(f"  Output Path:            {output_file}")
    print(f"  SHA-256 Hash:           {sha256_hash}")
    print(f"  File Size:              {file_size_mb:.2f} MB")
    print(f"  Total Data Rows:        {rows_written}")
    print(f"  Titles with Entities:   {titles_with_entities} ({(titles_with_entities / len(candidate_records)) * 100:.2f}%)")
    print(f"  Zero-Entity Titles:     {titles_without_entities} ({(titles_without_entities / len(candidate_records)) * 100:.2f}%)")
    print(f"  Total Pipeline Runtime: {total_runtime:.1f}s ({total_runtime / 60:.2f} min)")

    # 11. Standalone Validation
    print("\n==================================================")
    print("RUNNING STANDALONE SUBMISSION VALIDATOR")
    print("==================================================")
    is_valid, val_report = validate_submission_file(
        output_file,
        expected_min_record=candidate_records[0][0],
        expected_max_record=candidate_records[-1][0],
    )
    print_validation_report(val_report)
    if not is_valid:
        raise RuntimeError("Submission validation failed! Please check errors above.")

    print("\n>>> SUBMISSION VALIDATION PASSED 100% <<<")

    # Clean intermediate cache if requested
    if clean_cache_after and cache_dir is not None:
        for c_file in [gbert_cache, s42_cache, s7_cache, s21_cache]:
            if c_file is not None and c_file.exists():
                c_file.unlink()
        print("Cleaned intermediate probability caches to preserve disk space.")

    return {
        "output_path": str(output_file),
        "sha256": sha256_hash,
        "total_records": len(candidate_records),
        "total_rows": rows_written,
        "titles_with_entities": titles_with_entities,
        "titles_without_entities": titles_without_entities,
        "total_runtime_seconds": round(total_runtime, 1),
        "validation_passed": is_valid,
    }


